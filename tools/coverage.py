"""ATT&CK coverage: which techniques the detection set covers, at what maturity, against the threat profile.

Outputs (committed by CI so the repo always shows current numbers):
  coverage/navigator-layer.json  ATT&CK Navigator layer (score = maturity: draft 1, qa 2, prod 3)
  coverage/coverage.md           per-tactic table + per-technique list with the rules behind each
  coverage/gaps.md               profile techniques with no prod rule, ranked by priority and actor count
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from common import ROOT, STATUS_ORDER, load_attack, load_content, load_profile

OUT = ROOT / "coverage"
MATURITY = {"draft": 1, "qa": 2, "prod": 3}


def build():
    attack = load_attack(); profile = load_profile(); items = [r for _, r in load_content()]
    rules_by_tech: dict[str, list[dict]] = defaultdict(list)
    for r in items:
        if r.get("status") == "retired": continue
        for t in r["attack"]["techniques"]:
            rules_by_tech[t].append(r)
    maturity = {t: max(MATURITY[r["status"]] for r in rs) for t, rs in rules_by_tech.items()}

    # ---- Navigator layer
    techs = []
    for t, score in sorted(maturity.items()):
        rs = rules_by_tech[t]
        for ta in attack["techniques"].get(t, {}).get("tactics", []):
            techs.append({"techniqueID": t, "tactic": attack["tactics"][ta].lower().replace(" ", "-"), "score": score,
                          "comment": "; ".join(f"{r['id']} ({r['status']}, {r['platform']})" for r in rs), "enabled": True, "showSubtechniques": True})
    layer = {
        "name": "Detection coverage", "versions": {"attack": "17", "navigator": "5.1.0", "layer": "4.5"}, "domain": "enterprise-attack",
        "description": "Generated by tools/coverage.py. Score = best maturity of a rule for the technique: 1 draft, 2 qa, 3 prod.",
        "techniques": techs, "gradient": {"colors": ["#ffe0b2", "#ffb74d", "#2e7d32"], "minValue": 1, "maxValue": 3},
        "legendItems": [{"label": "draft", "color": "#ffe0b2"}, {"label": "qa", "color": "#ffb74d"}, {"label": "prod", "color": "#2e7d32"}],
        "layout": {"layout": "side", "showID": True, "showName": True}, "hideDisabled": False, "selectTechniquesAcrossTactics": True,
    }
    OUT.mkdir(exist_ok=True)
    (OUT / "navigator-layer.json").write_text(json.dumps(layer, indent=1), encoding="utf-8")

    # ---- coverage.md
    per_tactic: dict[str, dict[str, set]] = {ta: {"ref": set(), "cov": set(), "prod": set()} for ta in attack["tactics"]}
    for t, meta in attack["techniques"].items():
        for ta in meta["tactics"]:
            per_tactic[ta]["ref"].add(t)
            if t in maturity: per_tactic[ta]["cov"].add(t)
            if maturity.get(t) == 3: per_tactic[ta]["prod"].add(t)
    total_prod = sum(1 for r in items if r["status"] == "prod" and r["kind"] == "detection")
    md = ["# ATT&CK coverage", "", f"{len(items)} content items · {total_prod} detections in prod · "
          f"{len(maturity)} techniques covered ({sum(1 for v in maturity.values() if v == 3)} with a prod rule).",
          "", "Reference = techniques in `data/attack-techniques.json` (the curated set this profile cares about).", "",
          "| Tactic | Covered / reference | Prod | Techniques |", "|---|---|---|---|"]
    for ta, name in attack["tactics"].items():
        d = per_tactic[ta]
        if not d["ref"]: continue
        md.append(f"| {name} ({ta}) | {len(d['cov'])} / {len(d['ref'])} | {len(d['prod'])} | " +
                  ", ".join(f"{t}{'★' if maturity.get(t) == 3 else '☆' if t in maturity else ''}" for t in sorted(d['ref'])) + " |")
    md += ["", "★ prod rule · ☆ draft/qa only · none = gap", "", "## Techniques and the rules behind them", "",
           "| Technique | Name | Maturity | Rules |", "|---|---|---|---|"]
    for t in sorted(maturity):
        md.append(f"| {t} | {attack['techniques'][t]['name']} | {STATUS_ORDER[maturity[t]-1] if maturity[t] < 4 else ''} | " +
                  ", ".join(f"`{r['id']}`" for r in rules_by_tech[t]) + " |")
    (OUT / "coverage.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    # ---- gaps.md against the profile
    actor_count: dict[str, list[str]] = defaultdict(list)
    for a in profile["actors"]:
        for t in a["techniques"]: actor_count[t].append(a["name"])
    prio = profile["priority_techniques"]
    wanted = set(prio) | set(actor_count)
    rows = []
    for t in wanted:
        m = maturity.get(t, 0)
        if m == 3: continue
        rows.append((prio.get(t, 1) * 10 + len(actor_count.get(t, [])), t, m))
    rows.sort(reverse=True)
    g = ["# Coverage gaps against the threat profile", "", "Techniques the profile says matter (priority ≥ 1 or used by a tracked actor) "
         "that have **no prod rule**. Ranked by priority × actors. This is the detection backlog.", "",
         "| Rank | Technique | Name | Priority | Actors | Current |", "|---|---|---|---|---|---|"]
    for i, (_, t, m) in enumerate(rows, 1):
        g.append(f"| {i} | {t} | {attack['techniques'].get(t, {}).get('name', '?')} | {prio.get(t, '-')} | "
                 f"{', '.join(actor_count.get(t, [])) or '-'} | {STATUS_ORDER[m-1] if m else 'none'} |")
    covered_prio = sum(1 for t in prio if maturity.get(t) == 3)
    g += ["", f"Profile coverage: **{covered_prio} / {len(prio)}** priority techniques have a prod rule; "
          f"{len(rows)} gaps open."]
    (OUT / "gaps.md").write_text("\n".join(g) + "\n", encoding="utf-8")
    print(f"coverage: {len(maturity)} techniques, {covered_prio}/{len(prio)} priority covered, {len(rows)} gaps")
    return rows


if __name__ == "__main__":
    build()
